# --- Pydantic Models for Room Data Generation ---

# Model for time-specific descriptions within a room
class RoomTimeDescriptions(BaseModel):
    """
    Represents the time-of-day specific descriptions for a room.
    The field names are aliased to match the desired JSON keys with spaces.
    """
    late_night: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during late night hours.",
        alias="late night"
    )
    early_morning: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during early morning hours.",
        alias="early morning"
    )
    morning: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during morning hours.",
        alias="morning"
    )
    noon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during noon (midday) hours.",
        alias="noon"
    )
    afternoon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during afternoon hours.",
        alias="afternoon"
    )
    late_afternoon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during late afternoon hours.",
        alias="late afternoon"
    )
    night: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during night hours.",
        alias="night"
    )

# This Pydantic model defines the complete structure of a single room object.
# The AI will primarily generate the 'descriptions' part, other parts are placeholders or static for now.
class Room(BaseModel):
    name: str = Field(description="The unique identifier/name for the room.")
    image: str = Field(description="The image file name associated with the room.")
    room_types: List[str] = Field(description="A list of categories or types defining the room's nature (e.g., 'lab', 'social').")
    music: str = Field(description="The background music track associated with the room.")
    descriptions: RoomTimeDescriptions = Field(description="Time-of-day specific descriptions for the room, generated by AI.")
    items: List[Any] = Field(description="A list of items present in the room. This list is empty by default.")

    plots: int |None = Field(default=None, description="Optional, Only required for rooms of type 'planting_garden' Number of gardening plots for this room")
# --- Room Crafter Class ---

class room_crafter:

    def __init__(self, select_model="gpt-5-mini", select_provider="openai"):
        self.llm_client=AIConfiguration(provider=select_provider,model=select_model,mode="simple_ai").get_client()

    def _generate_room_descriptions(self, room_concept: str) -> RoomTimeDescriptions | None:
        """
        Generates the time-of-day specific descriptions for a room based on a concept.
        This uses the AI to fill the `RoomTimeDescriptions` Pydantic model.
        """
        system_prompt = (
            "You are a creative writter, world builder, tasked in crafting vivid, and evocative room descriptions "
            "for an interactive environment. For a given room concept, your task is to generate "
            "1-2 distinct descriptions for each of the following time slots: 'late night', 'early morning', "
            "'morning', 'noon', 'afternoon', 'late afternoon', and 'night'. "
            "Each description should capture the mood, lighting, activity level, and general atmosphere "
            "of the room at that specific time of day. "
            "Focus on sensory details and brevity (e.g., 1-2 sentences per description string)."
            "\n\nExample for a 'cozy study':"
            "\n{\"late night\": [\"The study is quiet, illuminated only by the soft glow of a desk lamp.\", \"A comfortable armchair invites a late-night read.\"]}"
            "\n\nEnsure that the mood and lighting of your descriptions evolve appropriately throughout the day."
            "\n\nMake sure to be consistent across the descriptions, the room provided and your different previous descriptions."
        )
        user_prompt = (
            f"Generate 1-2 concise descriptions for each time slot (late night, early morning, morning, noon, "
            f"afternoon, late afternoon, night) for a room concept: '{room_concept}'. "
            "Ensure the descriptions reflect the time of day and the overall concept."
        )

        print(f"  Calling AI to generate descriptions for room concept: '{room_concept}'...")
        response = self.llm_client.structured_output(
            system=system_prompt,
            user=user_prompt,
            structure=RoomTimeDescriptions # The AI will generate data that fits this Pydantic model
        )
        return response
    def create_single_room_data(self, room_concept: str, room_name: str, room_image: str, room_types: List[str], room_music: str, plots: int | None = None) -> Dict[str, Any] | None:
        """
        Orchestrates the generation of room descriptions and assembles the complete room data dictionary.
        The AI generates the 'descriptions' part, while other fields are provided statically.
        """
        print(f"\n--- Initiating Room Data Generation for Concept: '{room_concept}' (Name: '{room_name}') ---")

        # Step 1: Generate the time-based descriptions using AI
        descriptions_model = self._generate_room_descriptions(room_concept)

        if not descriptions_model:
            print("Critical failure: Could not generate room descriptions. Aborting room data creation.")
            return None

        # Convert the Pydantic descriptions model into a dictionary, respecting the aliases
        # This will convert 'late_night' field to 'late night' key in the dictionary.
        descriptions_dict = descriptions_model.model_dump(by_alias=True)

        # Step 2: Assemble the full room dictionary with the AI-generated descriptions
        full_room_data = {
            "name": room_name,
            "image": room_image,
            "room_types": room_types,
            "music": room_music,
            "descriptions": descriptions_dict,
            "items": [] # As per instruction, leave empty but initialized
        }
        
        # Step 3: Conditionally add the 'plots' key if a value was provided.
        if plots is not None:
            full_room_data["plots"] = plots

        print(f"--- Room Data Generation Complete for Room: '{room_name}' ---")
        return full_room_data

    def append_room_to_file(self, file_path: str, new_room_data: Dict[str, Any]) -> bool:
        """
        Loads existing room data from a JSON file (expected to be a list of room objects),
        appends a new room's data, and saves the combined list back to the same file.
        This ensures a single, continuously growing file.

        Args:
            file_path: The path to the JSON file where room data is stored.
            new_room_data: A dictionary containing the data for one new room.

        Returns:
            True if the append and save operation was successful, False otherwise.
        """
        combined_rooms: List[Dict[str, Any]] = []

        # 1. Load existing data from the file
        try:
            with open(file_path, 'r') as f:
                try:
                    loaded_data = json.load(f)
                    if isinstance(loaded_data, list):
                        combined_rooms = loaded_data
                    else:
                        print(f"Warning: File '{file_path}' contains data that is not a list of rooms. Starting file with new data.")
                        combined_rooms = [] # Start fresh if content is not a list
                except json.JSONDecodeError:
                    print(f"Warning: File '{file_path}' contains invalid JSON or is empty. Starting file with new data.")
                    combined_rooms = [] # Start fresh if JSON is invalid or file is empty
                except Exception as e:
                    print(f"An unexpected error occurred while reading '{file_path}': {e}")
                    combined_rooms = [] # Fallback on other errors

        except FileNotFoundError:
            print(f"Info: File '{file_path}' not found. Creating a new file.")
            combined_rooms = [] # Start with an empty list if file doesn't exist

        # 2. Append the new room data
        if new_room_data:
            combined_rooms.append(new_room_data)
            print(f"Appended data for room: '{new_room_data.get('name', 'Unnamed Room')}' to list.")
        else:
            print("Warning: No new room data provided to append.")
            return False

        # 3. Save the combined data back to the file
        try:
            with open(file_path, 'w') as f:
                json.dump(combined_rooms, f, indent=4) # Use indent for pretty printing
            print(f"Successfully saved combined room data to '{file_path}'.")
            return True
        except Exception as e:
            print(f"Error writing room data to file '{file_path}': {e}")
            return False

# --- Example Usage ---
if __name__ == "__main__":
    crafter = room_crafter()
    room_data_file = "inventory_items/base_state_manager/houses_data/base_dev_room.json" # Define the path to your room data file

    # Define a list of room configurations. Each entry will generate one room.
    # The 'concept' is what the AI uses to generate descriptions.
    # 'name', 'image', 'types', 'music' are static metadata for the room.
    room_configs = [
        {"concept": "A lush garden, bursting with greenery and color. Cozy.",
         "name": "garden",
         "image": "garden",
         "types": ["garden"],
         "music": "garden"},


        {"concept": "A secluded, quiet laboratory with many vats full of liquid, a small glass trapdoor with a view to the outside on the roof, ",
         "name": "DevRoom",
         "image": "lab_room",
         "types": ["planting_garden","library"],
         "music": "white_room"},
    ]
    total_rooms = len(room_configs)

    # Loop through each room concept to generate and append its data
    for index, config in enumerate(room_configs):
        current_room_number = index + 1

        room_concept = config["concept"]
        room_name = config["name"]
        room_image = config["image"]
        room_types = config["types"]
        room_music = config["music"]

        # Print the generation message with the current number and total
        print(f"\n--- Generating and Appending Room: '{room_name}' ({current_room_number} of {total_rooms}) ---")

        # Generate data for a single room
        generated_room_data = crafter.create_single_room_data(
            room_concept=room_concept,
            room_name=room_name,
            room_image=room_image,
            room_types=room_types,
            room_music=room_music
        )

        if generated_room_data:
            # Append the newly generated room data to the file
            success = crafter.append_room_to_file(room_data_file, generated_room_data)
            if success:
                print(f"'{room_name}' data successfully added to '{room_data_file}'.")
                # Pause between generations, but not after the last one
                if current_room_number < total_rooms:
                    print(f"Successfully processed '{room_name}' ({current_room_number} of {total_rooms}).")
                    print("Sleeping for 10 seconds before generating the next room...")
                    time.sleep(10)
            else:
                print(f"Failed to add '{room_name}' data to '{room_data_file}'.")
        else:
            print(f"'{room_name}' data generation failed entirely.")

    print("\nAll requested room data generation and appending finalized!")