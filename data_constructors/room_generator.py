# --- Pydantic Models for Room Data Generation ---

VALID_ROOM_TYPES=["planting_garden","library","bedroom","living_room","bathroom","garden","white_room","kitchen","ALIFE_research"]

class RoomConfig(BaseModel):
    """Represents a single room configuration to be generated."""
    concept: str = Field(description="A detailed concept description for the room")
    name: str = Field(description="A unique identifier/name for the room")
    image: str = Field(description="The image filename (without extension) for the room")
    types: List[str] = Field(description=f"Room types from: {VALID_ROOM_TYPES}")
    music: str = Field(description="The music filename (without extension) for the room")
    plots: Optional[int] = Field(default=None, description="Number of plots if room type includes 'planting_garden'")

class HouseConfig(BaseModel):
    """Represents the complete house configuration."""
    house_name: str = Field(description="A creative name for the entire house/building")
    rooms: List[RoomConfig] = Field(description="List of room configurations for this house")

# Model for time-specific descriptions within a room
class RoomTimeDescriptions(BaseModel):
    """
    Represents the time-of-day specific descriptions for a room.
    The field names are aliased to match the desired JSON keys with spaces.
    """
    late_night: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during late night hours.",
        alias="late night"
    )
    early_morning: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during early morning hours.",
        alias="early morning"
    )
    morning: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during morning hours.",
        alias="morning"
    )
    noon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during noon (midday) hours.",
        alias="noon"
    )
    afternoon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during afternoon hours.",
        alias="afternoon"
    )
    late_afternoon: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during late afternoon hours.",
        alias="late afternoon"
    )
    night: List[str] = Field(
        description="A list of 1-2 distinct descriptions for the room during night hours.",
        alias="night"
    )

# This Pydantic model defines the complete structure of a single room object.
# The AI will primarily generate the 'descriptions' part, other parts are placeholders or static for now.
class Room(BaseModel):
    name: str = Field(description="The unique identifier/name for the room.")
    image: str = Field(description="The image file name associated with the room.")
    room_types: List[str] = Field(description=f"A list of these specific categories or types: {", ".join(VALID_ROOM_TYPES)}.")
    music: str = Field(description="The background music track associated with the room.")
    descriptions: RoomTimeDescriptions = Field(description="Time-of-day specific descriptions for the room, generated by AI.")
    items: List[Any] = Field(description="A list of items present in the room. This list is empty by default.")
    plots: int | None = Field(default=None, description="Optional, Only required for rooms of type 'planting_garden' Number of gardening plots for this room")

# --- Room Crafter Class ---

class room_crafter:

    def __init__(self, select_model="gpt-5-mini", select_provider="openai", signal_queue=None, images_model=None, images_provider=None):
        self.llm_client = AIConfiguration(provider=select_provider, model=select_model, mode="simple_ai").get_client()
        
        self.images_client = None
        if images_model and images_provider:
            self.images_client = ImagesConfiguration(provider=images_provider, model=images_model).get_image_generator()

        # Add shutdown mechanism
        self.signal_queue = signal_queue
        self._shutdown_event = threading.Event()
        self._current_operation = None

    # CHANGED: Simplified to only manage its internal state. No redundant signal.
    def request_shutdown(self):
        """Request shutdown from an external thread (e.g., BaseCrafter)."""
        if not self._shutdown_event.is_set():
            print("🛑 Room Crafter shutdown requested...")
            self._shutdown_event.set()


    def is_shutdown_requested(self):
        """Check if shutdown has been requested"""
        return self._shutdown_event.is_set()

    def _check_shutdown(self, operation_name=""):
        """Check for shutdown request and handle if needed"""
        if self.is_shutdown_requested():
            print(f"🛑 Room Crafter shutdown detected during: {operation_name}")
            return True
        return False

    # NEW: Signal sending helper, consistent with BaseCrafter
    def _send_signal(self, signal, data=None):
        """Send a signal if a queue is available."""
        if self.signal_queue:
            try:
                self.signal_queue.put((signal, data))
            except Exception as e:
                # Don't let a failed signal stop the process
                print(f"Warning: room_crafter failed to send signal {signal}: {e}")




    def _generate_room_descriptions(self, room_concept: str) -> RoomTimeDescriptions | None:
        """
        Generates the time-of-day specific descriptions for a room based on a concept.
        Now with shutdown support.
        """
        # Check shutdown before expensive AI operation
        if self._check_shutdown(f"generating_descriptions_for_{room_concept}"):
            return None

        system_prompt = (
            "You are a creative writter, world builder, tasked in crafting vivid, and evocative room descriptions "
            "for an interactive environment. For a given room concept, your task is to generate "
            "1-2 distinct descriptions for each of the following time slots: 'late night', 'early morning', "
            "'morning', 'noon', 'afternoon', 'late afternoon', and 'night'. "
            "Each description should capture the mood, lighting, activity level, and general atmosphere "
            "of the room at that specific time of day. "
            "Focus on sensory details and brevity (e.g., 1-2 sentences per description string)."
            "\n\nExample for a 'cozy study':"
            "\n{\"late night\": [\"The study is quiet, illuminated only by the soft glow of a desk lamp.\", \"A comfortable armchair invites a late-night read.\"]}"
            "\n\nEnsure that the mood and lighting of your descriptions evolve appropriately throughout the day."
            "\n\nMake sure to be consistent across the descriptions, the room provided and your different previous descriptions."
        )
        user_prompt = (
            f"Generate 1-2 concise descriptions for each time slot (late night, early morning, morning, noon, "
            f"afternoon, late afternoon, night) for a room concept: '{room_concept}'. "
            "Ensure the descriptions reflect the time of day and the overall concept."
        )

        print(f"  Calling AI to generate descriptions for room concept: '{room_concept}'...")
        
        try:
            response = self.llm_client.structured_output(
                system=system_prompt,
                user=user_prompt,
                structure=RoomTimeDescriptions
            )
            
            # Check shutdown after AI call
            if self._check_shutdown(f"after_descriptions_for_{room_concept}"):
                return None
                
            return response
        except Exception as e:
            print(f"❌ Error generating room descriptions: {e}")
            return None

    # CHANGED: Added a flavor text signal
    def create_single_room_data(self, room_concept: str, room_name: str, room_image: str, room_types: List[str], room_music: str, plots: int | None = None) -> Dict[str, Any] | None:
        if self._check_shutdown(f"creating_room_data_{room_name}"):
            return None

        print(f"\n--- Initiating Room Data Generation for Concept: '{room_concept}' (Name: '{room_name}') ---")
        
        # NEW: Send flavor text
        self._send_signal(CrafterSignal.FLAVOR_TEXT, f"Imagining the details of the {room_name}...")

        descriptions_model = self._generate_room_descriptions(room_concept)
        if self._check_shutdown(f"after_descriptions_{room_name}"):
            return None
        if not descriptions_model:
            print("Critical failure: Could not generate room descriptions. Aborting room data creation.")
            return None

        descriptions_dict = descriptions_model.model_dump(by_alias=True)
        full_room_data = {
            "name": room_name, "image": room_image, "room_types": room_types,
            "music": room_music, "descriptions": descriptions_dict, "items": []
        }
        if plots is not None:
            full_room_data["plots"] = plots

        print(f"--- Room Data Generation Complete for Room: '{room_name}' ---")
        return full_room_data

    def append_room_to_file(self, file_path: str, new_room_data: Dict[str, Any]) -> bool:
        """
        Loads existing room data from a JSON file, appends new room's data, and saves back.
        Now with shutdown support.
        """
        # Check shutdown at start
        if self._check_shutdown(f"appending_to_file_{file_path}"):
            return False

        combined_rooms: List[Dict[str, Any]] = []

        # 1. Load existing data from the file
        try:
            with open(file_path, 'r') as f:
                try:
                    loaded_data = json.load(f)
                    if isinstance(loaded_data, list):
                        combined_rooms = loaded_data
                    else:
                        print(f"Warning: File '{file_path}' contains data that is not a list of rooms. Starting file with new data.")
                        combined_rooms = []
                except json.JSONDecodeError:
                    print(f"Warning: File '{file_path}' contains invalid JSON or is empty. Starting file with new data.")
                    combined_rooms = []
                except Exception as e:
                    print(f"An unexpected error occurred while reading '{file_path}': {e}")
                    combined_rooms = []

        except FileNotFoundError:
            print(f"Info: File '{file_path}' not found. Creating a new file.")
            combined_rooms = []

        # Check shutdown after file reading
        if self._check_shutdown(f"after_reading_file_{file_path}"):
            return False
        
        self._send_signal(CrafterSignal.FLAVOR_TEXT, "Consulting the architectural AI...")


        # 2. Append the new room data
        if new_room_data:
            combined_rooms.append(new_room_data)
            print(f"Appended data for room: '{new_room_data.get('name', 'Unnamed Room')}' to list.")
        else:
            print("Warning: No new room data provided to append.")
            return False

        # Check shutdown before writing
        if self._check_shutdown(f"before_writing_file_{file_path}"):
            return False

        # 3. Save the combined data back to the file
        try:
            with open(file_path, 'w') as f:
                json.dump(combined_rooms, f, indent=4)
            print(f"Successfully saved combined room data to '{file_path}'.")
            return True
        except Exception as e:
            print(f"Error writing room data to file '{file_path}': {e}")
            return False
            
    def scan_asset_directories(self, image_dirs: List[str], music_dirs: List[str]) -> tuple[List[str], List[str]]:
        """
        Scans directories for available image and music assets.
        Now with shutdown support.
        """
        # Check shutdown at start
        if self._check_shutdown("scanning_asset_directories"):
            return [], []

        available_images = []
        available_music = []
        
        # Scan image directories for common image formats
        image_extensions = ['*.jpg']
        for img_dir in image_dirs:
            if self._check_shutdown(f"scanning_image_dir_{img_dir}"):
                return available_images, available_music
                
            if os.path.exists(img_dir):
                for ext in image_extensions:
                    files = glob.glob(os.path.join(img_dir, ext))
                    for file in files:
                        # Get filename without extension
                        filename = os.path.splitext(os.path.basename(file))[0]
                        if filename not in available_images:
                            available_images.append(filename)
        
        # Scan music directories for common audio formats
        music_extensions = ['*.mp3']
        for music_dir in music_dirs:
            if self._check_shutdown(f"scanning_music_dir_{music_dir}"):
                return available_images, available_music
                
            if os.path.exists(music_dir):
                for ext in music_extensions:
                    files = glob.glob(os.path.join(music_dir, ext))
                    for file in files:
                        # Get filename without extension
                        filename = os.path.splitext(os.path.basename(file))[0]
                        if filename not in available_music:
                            available_music.append(filename)
        
        return available_images, available_music

    def generate_rooms_config(self, initial_idea: str,
                            image_dirs: List[str] = None,
                            music_dirs: List[str] = None,
                            max_rooms: int = 8) -> HouseConfig | None:
        """
        Given a singular idea, the AI will create room configs.
        If an image generator (self.images_client) is available, it will generate,
        save, and assign a unique image for each room. Otherwise, it will select
        from pre-existing assets.
        """
        if self._check_shutdown("generating_rooms_config"):
            return None

        # Set default directories if none provided
        if image_dirs is None:
            image_dirs = ["style/images/rooms_images", "style/images/local_rooms_images", "style/images/local_rooms_images/local_ai_gens"]
        if music_dirs is None:
            music_dirs = ["style/sounds/music/rooms", "style/sounds/local_music/rooms"]

        # --- Base Prompt Setup ---
        user_prompt = (
            f"Create a house design based on this concept: '{initial_idea}'\n\n"
            "Generate:\n"
            "1. A creative house name that captures the essence of the concept.\n"

            f"2. Between 3 and {max_rooms} rooms that work together to create a cohesive experience.\n"
            "3. Each room should have varied purposes and atmospheres while fitting the overall theme.\n\n"
            "Make sure room names are unique, concepts are detailed and evocative, and asset assignments make thematic sense."
        )

        system_prompt_base = (
            "You are a creative house designer and world builder. Given an initial concept, you will create "
            "a cohesive house design with multiple rooms that fit the theme. Generate both a creative name "
            "for the house and detailed room configurations.\n\n"
            f"Available room types: {', '.join(VALID_ROOM_TYPES)}\n"
        )

        # --- Conditional Behavior: Generate Images vs. Use Assets ---
        if self.images_client:
            # BEHAVIOR 1: We have an image generator.
            print("Image generator detected. Will generate new images for rooms.")
            _, available_music = self.scan_asset_directories([], music_dirs)
            
            system_prompt = (
                system_prompt_base +
                f"Available music: {', '.join(available_music) if available_music else 'No music found - use generic names'}\n\n"
                "For each room:\n"
                "- Create a unique, descriptive concept (2-3 sentences). This concept will be used to generate an image.\n"
                "- Assign a short, unique name (no spaces, lowercase with underscores).\n"
                "- You DO NOT need to assign an image name. Use 'ai_generated_image' as a placeholder for the 'image' field.\n"
                "- Choose appropriate music from the available assets.\n"
                "- Select relevant room types from the valid list.\n"
                "- If room type includes 'planting_garden', specify number of plots (1-20)."
            )
            
        else:
            # BEHAVIOR 2: No image generator. Use existing assets.
            print("No image generator detected. Will use existing assets.")
            available_images, available_music = self.scan_asset_directories(image_dirs, music_dirs)
            if self._check_shutdown("after_asset_scanning"):
                return None
            print(f"Found {len(available_images)} available images and {len(available_music)} available music tracks")
            
            system_prompt = (
                system_prompt_base +
                f"Available images: {', '.join(available_images) if available_images else 'No images found - use generic names'}\n"
                f"Available music: {', '.join(available_music) if available_music else 'No music found - use generic names'}\n\n"
                "For each room:\n"
                "- Create a unique, descriptive concept (2-3 sentences).\n"
                "- Assign a short, unique name (no spaces, lowercase with underscores).\n"
                "- Choose an appropriate image and music from the available asset lists.\n"
                "- Select relevant room types from the valid list.\n"
                "- If room type includes 'planting_garden', specify number of plots (1-20)."
            )

        # --- AI Call to Generate House Structure ---
        print(f"Generating house configuration for concept: '{initial_idea}'...")
        try:
            response = self.llm_client.structured_output(
                system=system_prompt,
                user=user_prompt,
                structure=HouseConfig
            )
            if self._check_shutdown("after_house_config_generation"):
                return None
        except Exception as e:
            print(f"Error generating house configuration: {e}")
            return None

        if not response or not response.rooms:
            print("Failed to generate valid house configuration.")
            return None

        print(f"Generated house structure for '{response.house_name}' with {len(response.rooms)} rooms.")

        # --- Post-Processing: Generate Images if Needed ---
        if self.images_client:
            safe_house_name = re.sub(r'[^a-zA-Z0-9_-]', '_', response.house_name.lower())
            gen_image_dir = "style/images/local_rooms_images/local_ai_gens"
            os.makedirs(gen_image_dir, exist_ok=True)
            print(f"Saving generated images to '{gen_image_dir}'")

            for room in response.rooms:
                if self._check_shutdown(f"image_generation_for_{room.name}"):
                    return None

                try:
                    self._send_signal(CrafterSignal.FLAVOR_TEXT, f"Painting a picture of the {room.name}...")
                    image_prompt = f"Interior design, rough black and white graphite sketch. No words or writings. {room.concept}"
                    image_filename_no_ext = f"{safe_house_name}_{room.name}"
                    image_save_path = os.path.join(gen_image_dir, f"{image_filename_no_ext}.jpg")
                    
                    print(f"  Generating image for '{room.name}'...")
                    image_bytes = self.images_client.generate_image(image_prompt)
                    
                    if self._check_shutdown(f"after_image_bytes_for_{room.name}"):
                        return None
                        
                    with open(image_save_path, 'wb') as f:
                        f.write(image_bytes)
                    
                    room.image = image_filename_no_ext  # Update the room config with the new filename
                    print(f"  ✓ Saved image to '{image_save_path}'")
                except Exception as e:
                    print(f"  ❌ Failed to generate or save image for room '{room.name}': {e}")
                    # The room will keep its placeholder image name, which can be handled downstream
        
        # --- Final Output ---
        print("House configuration generation complete.")
        for i, room in enumerate(response.rooms, 1):
            print(f"  {i}. {room.name} (Image: '{room.image}.jpg', Types: {', '.join(room.types)})")
        return response

    def orchestrate_generation(self, initial_idea: str, 
                            output_dir: str = "inventory_items/base_state_manager/houses_data/local_ai_gen",
                            image_dirs: List[str] = None, 
                            music_dirs: List[str] = None) -> Dict[str, Any] | None:
        """
        Uses generate_rooms_config and the AI generated initial config for the complete process.
        Now with shutdown support.
        """
        print(f"\n=== ORCHESTRATING HOUSE GENERATION ===")
        print(f"Initial concept: '{initial_idea}'")
        
        # Reset shutdown state and partial data for new generation
        self._shutdown_event.clear()
        self._current_operation = "house_orchestration"
        
        # Check shutdown at start
        if self._check_shutdown("orchestration_start"):
            return None
        
        # Step 1: Generate the house configuration
        house_config = self.generate_rooms_config(initial_idea, image_dirs, music_dirs)
        
        if self._check_shutdown("after_house_config"):
            return None
        
        if not house_config:
            print("Failed to generate house configuration. Aborting orchestration.")
            return None
        
        self._send_signal(CrafterSignal.FLAVOR_TEXT, f"Now building '{house_config.house_name}'...")

        # Step 2: Set up output file path
        os.makedirs(output_dir, exist_ok=True)
        safe_house_name = re.sub(r'[^a-zA-Z0-9_-]', '_', house_config.house_name.lower())
        file_path = os.path.join(output_dir, f"{safe_house_name}.json")
        
        
        # Step 3: Generate detailed room data for each room
        all_room_data = []
        total_rooms = len(house_config.rooms)
        
        for index, room_config in enumerate(house_config.rooms):
            current_room_number = index + 1

            self._send_signal(CrafterSignal.FLAVOR_TEXT, f"Raising the walls for the {room_config.name}...")

            
            print(f"\n--- Processing Room {current_room_number}/{total_rooms}: '{room_config.name}' ---")
            
            # Generate the full room data
            room_data = self.create_single_room_data(
                room_concept=room_config.concept,
                room_name=room_config.name,
                room_image=room_config.image,
                room_types=room_config.types,
                room_music=room_config.music,
                plots=room_config.plots
            )
            
            if room_data:
                all_room_data.append(room_data)
                print(f"✓ Successfully generated room: '{room_config.name}'")
                
                # Add delay between rooms (except for the last one) with shutdown checks
                if current_room_number < total_rooms:
                    print("Pausing 5 seconds before next room...")
                    for i in range(5):  # Check shutdown every second during delay
                        if self._check_shutdown(f"delay_after_room_{room_config.name}"):
                            return None
                        time.sleep(1)
            else:
                print(f"✗ Failed to generate room: '{room_config.name}'")
        
        # Check shutdown before saving
        if self._check_shutdown("before_final_save"):
            return None
        
        # Step 4: Save all room data to file
        if all_room_data:
            try:
                with open(file_path, 'w') as f:
                    json.dump(all_room_data, f, indent=4)
                print(f"\n✓ Successfully saved {len(all_room_data)} rooms to '{file_path}'")
            except Exception as e:
                print(f"✗ Error saving to file: {e}")
                return None
        else:
            print("No room data was successfully generated.")
            return None
        
        # Step 5: Create and return the summary
        generation_summary = {
            "total_rooms_planned": total_rooms,
            "total_rooms_generated": len(all_room_data),
            "room_names": [room["name"] for room in all_room_data],
            "room_types_used": list(set([t for room in all_room_data for t in room["room_types"]])),
            "success_rate": f"{len(all_room_data)}/{total_rooms} ({len(all_room_data)/total_rooms*100:.1f}%)"
        }
        
        result = {
            "house_name": house_config.house_name,
            "file_path": file_path,
            "room_data": all_room_data,
            "generation_summary": generation_summary
        }
        
        # Final check before completion
        if self._check_shutdown("before_result_return"):
            return None
        
        # Print final summary
        print(f"\n=== GENERATION COMPLETE ===")
        print(f"House: {house_config.house_name}")
        print(f"Rooms generated: {generation_summary['success_rate']}")
        print(f"File saved: {file_path}")
        print(f"Room types: {', '.join(generation_summary['room_types_used'])}")
    
        
        return result
